from __future__ import annotations

from collections.abc import Awaitable, Callable, Mapping
from typing import Protocol, runtime_checkable

from . import RuntimeService
from .activities import ActivityContext, ActivityRequest
from .connections import ContractKey, Usage
from .hybrid import HybridSettings, StreamEvent, StreamOptions, StreamState


@runtime_checkable
class StreamReceiverProtocol(Protocol):
    @property
    def options(self) -> StreamOptions: ...
    @property
    def state(self) -> StreamState: ...
    @property
    def reason(self) -> str | None: ...
    @property
    def buffered_bytes(self) -> int: ...
    @property
    def buffered_chunks(self) -> int: ...
    async def receive(self, *, timeout) -> StreamEvent: ...
    async def abort(self, reason="Explicit stream abort") -> None: ...
    async def fail(self, reason) -> None: ...
    async def aclose(self) -> None: ...


@runtime_checkable
class StreamSenderProtocol(Protocol):
    @property
    def options(self) -> StreamOptions: ...
    @property
    def state(self) -> StreamState: ...
    @property
    def reason(self) -> str | None: ...
    @property
    def buffered_bytes(self) -> int: ...
    @property
    def buffered_chunks(self) -> int: ...
    @property
    def dropped_chunks(self) -> int: ...
    async def send(self, data: bytes | bytearray | memoryview, *, timeout) -> int: ...
    async def close(self, *, timeout) -> None: ...
    async def abort(self, reason="Explicit stream abort") -> None: ...
    async def fail(self, reason) -> None: ...
    async def aclose(self) -> None: ...


@runtime_checkable
class DirectLinkProtocol(Protocol):
    @property
    def pending_requests(self) -> tuple[str, ...]: ...
    def result(self, request_id): ...
    def release(self, request_id) -> None: ...
    async def acall(self, operation, *args, timeout, **kwargs): ...
    async def open_stream(self, operation, options: StreamOptions, metadata=None, *, timeout) -> StreamSenderProtocol: ...
    async def close(self) -> None: ...


@runtime_checkable
class CoreClientProtocol(Protocol):
    @property
    def pending_requests(self) -> tuple[str, ...]: ...
    def result(self, request_id): ...
    def release(self, request_id) -> None: ...
    async def candidates(self, contract: ContractKey, *, timeout=None): ...
    async def bind(self, contract: ContractKey, provider_id: str, *, timeout): ...
    async def prepare(self, contract: ContractKey, *, timeout) -> DirectLinkProtocol: ...
    async def invoke(self, contract: ContractKey, operation, *args, timeout, **kwargs): ...
    async def publish_usage(self, usage: Usage, *, contracts=None, timeout=None): ...
    async def health_check(self, *, module_ids=None, bindings=None, timeout=None): ...
    async def next_notice(self, *, timeout): ...
    async def acknowledge_interruption(self, notice_id, *, timeout=None): ...
    async def submit_remote(self, request: ActivityRequest, module_id, executor_id, arguments=None, *, timeout=None): ...
    async def activity(self, operation, key=None, *, timeout=None, **arguments): ...


@runtime_checkable
class ModuleContextProtocol(Protocol):
    """Core-owned context. Register handlers in the factory or start only."""
    @property
    def module_id(self) -> str: ...
    @property
    def generation(self) -> str: ...
    @property
    def settings(self) -> HybridSettings: ...
    @property
    def core(self) -> CoreClientProtocol: ...
    def provide(self, contract: ContractKey, handlers: Mapping[str, Callable[..., Awaitable[object]]]) -> None: ...
    def provide_stream(self, contract: ContractKey, operation: str,
                       handler: Callable[[StreamReceiverProtocol, object], Awaitable[None]]) -> None: ...
    def provide_executor(self, executor_id: str,
                         handler: Callable[[ActivityContext, object], Awaitable[object]], *, supports_pause=False) -> None: ...


class ModuleFactory(Protocol):
    def __call__(self, context: ModuleContextProtocol, config: object) -> RuntimeService[object] | Awaitable[RuntimeService[object]]: ...
